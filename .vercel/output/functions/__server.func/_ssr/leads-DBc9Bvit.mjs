function exportToCSV(leads, profileMap, filename) {
  const headers = ["Name", "Phone", "Email", "Property Interest", "Budget", "Priority", "Status", "Source", "Address", "Follow-up Date", "Assigned To", "Notes", "Created At"];
  const rows = leads.map((l) => [l.name ?? "", l.phone ?? "", l.email ?? "", l.property_interest ?? "", l.budget ?? "", l.priority ?? "", STATUS_LABEL[l.status] ?? l.status ?? "", (l.source ?? "").replace(/_/g, " "), l.address ?? "", l.follow_up_date ?? "", profileMap[l.employee_id]?.name ?? "", (l.notes ?? "").replace(/\n/g, " "), formatDate(l.created_at)]);
  const csvContent = [headers, ...rows].map((row) => row.map((cell) => `"${String(cell).replace(/"/g, '""')}"`).join(",")).join("\n");
  const blob = new Blob([csvContent], {
    type: "text/csv;charset=utf-8;"
  });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
